import { send, stop } from '@/lib/engine';
import { useChat } from '@/store/chat';
import { useSettings, activeModelId } from '@/store/settings';
import { parseBlocks } from '@/components/markdown-parse';
import { modelForLevel } from '@/data/models';
let fails = 0;
const assert = (c: unknown, msg: string) => { if (!c) { fails++; console.error('FALLO -', msg); } else console.log('ok    -', msg); };
(async () => {
  assert(modelForLevel('lite').id === 'phi-3.5-mini' && modelForLevel('pro').id === 'qwen3-1.7b' && modelForLevel('max').id === 'cybersecqwen-4b', 'mapeo nivel → modelo');
  useSettings.getState().setLevel('max'); useSettings.getState().setMode('red');
  assert(activeModelId(useSettings.getState()) === 'cybersecqwen-4b', 'modelo activo sigue al nivel');
  useSettings.getState().setModelOverride('lfm3-1.7b');
  assert(activeModelId(useSettings.getState()) === 'lfm3-1.7b', 'override manual (LFM3)');
  useSettings.getState().setLevel('pro');
  assert(useSettings.getState().modelOverride === null, 'cambiar nivel limpia override');
  const id = await send('¿Qué ecuaciones describen un sistema de tres cuerpos?');
  const c = useChat.getState().conversations.find((x) => x.id === id)!;
  assert(c.messages.length === 2, 'mensaje usuario + IA');
  assert(c.messages[1]!.status === 'done' && c.messages[1]!.content.includes('Qwen3 1.7B'), 'streaming completo con el modelo correcto');
  assert((c.messages[1]!.thinkMs ?? 0) > 0, 'registra tiempo de pensamiento');
  assert(c.title.startsWith('¿Qué ecuaciones'), 'título automático');
  assert(c.agent.mode === 'red' && c.agent.level === 'pro', 'instantánea del agente');
  const p = send('segundo mensaje', id); setTimeout(() => stop(id), 900); await p;
  const m = useChat.getState().conversations.find((x) => x.id === id)!.messages;
  assert(m.length === 4 && m[3]!.status === 'stopped', 'detener generación');
  const b = parseBlocks('hola **x**\n\n```ts\nconst a = 1;\n```\nfin');
  assert(b.length === 3 && b[1]!.kind === 'code' && (b[1] as { lang: string }).lang === 'ts', 'parser markdown');
  assert(parseBlocks('```py\nprint(1)').length === 1, 'bloque de código sin cerrar (streaming)');
  useChat.getState().remove(id);
  assert(useChat.getState().conversations.length === 0 && useChat.getState().activeId === null, 'borrar conversación');
  console.log(fails ? `${fails} FALLOS` : 'TODO OK');
  process.exit(fails ? 1 : 0);
})();
